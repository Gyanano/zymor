from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from zymor.model.node import CATEGORIES, LAYERS
from zymor.store.index import Index
from zymor.tokenizer import estimate_tokens
from zymor.util.fs import atomic_write_text
from zymor.vault import Vault

GENERATED_HEADER = "<!-- generated by zymor; do not edit -->"
CATALOG_LINE_BUDGET = 60
CATALOG_LINE_LIMIT = 80
ATLAS_MAX_LINES = 200
ATLAS_RECENT_LIMIT = 20
ATLAS_TAG_LIMIT = 100
STATUSES = ("hypothesis", "verified", "disputed", "deprecated")

CATALOG_RE = re.compile(
    r"^- \[(?P<title>.+?)\]\((?P<link>[^)]*)\)"
    r" · (?P<node_id>[^·]*) · (?P<status>[^·]*)"
    r" · (?P<confidence>[^·]*) · (?P<updated_at>.+)$"
)


@dataclass
class CatalogEntry:
    title: str
    link: str
    node_id: str | None
    status: str
    confidence: float | None
    updated_at: str
    raw: str

    def to_dict(self) -> dict[str, Any]:
        """入参：无。出参：目录行字典（browse 工具用）。"""
        return {
            "title": self.title,
            "link": self.link,
            "id": self.node_id,
            "status": self.status,
            "confidence": self.confidence,
            "updated_at": self.updated_at,
        }


def catalog_path(vault: Vault, category: str) -> Path:
    """入参：vault 与分类。出参：该分类 catalog 文件路径。"""
    return vault.nodes_dir / category / "_catalog.md"


def _fit_title(title: str, fixed: str) -> str:
    available = CATALOG_LINE_BUDGET - estimate_tokens(fixed)
    if available <= 2:
        return ""
    if estimate_tokens(title) <= available:
        return title
    kept: list[str] = []
    for char in title:
        candidate = "".join(kept) + char
        if estimate_tokens(candidate + "…") > available:
            break
        kept.append(char)
    return "".join(kept) + "…"


def render_catalog_line(
    node_id: str,
    title: str,
    status: str,
    confidence: float,
    updated_at: str,
) -> str:
    """入参：节点元数据。出参：catalog 行（≤60 tokens 目标、≤80 上限）。"""
    fixed = f"- []({node_id}.md) · {node_id} · {status} · {confidence:.2f} · {updated_at}"
    fitted = _fit_title(title, fixed)
    line = f"- [{fitted}]({node_id}.md) · {node_id} · {status} · {confidence:.2f} · {updated_at}"
    if estimate_tokens(line) > CATALOG_LINE_LIMIT:
        line = line[:CATALOG_LINE_LIMIT]
    return line


def parse_catalog_line(line: str) -> CatalogEntry | None:
    """入参：catalog 文本行。出参：解析结果；不是 catalog 行时返回 None。"""
    match = CATALOG_RE.match(line.strip())
    if match is None:
        return None
    node_id = match.group("node_id").strip() or None
    link = match.group("link").strip()
    if node_id is None and link.endswith(".md"):
        node_id = Path(link).stem or None
    confidence_text = match.group("confidence").strip()
    try:
        confidence = float(confidence_text)
    except ValueError:
        confidence = None
    return CatalogEntry(
        title=match.group("title"),
        link=link,
        node_id=node_id,
        status=match.group("status").strip(),
        confidence=confidence,
        updated_at=match.group("updated_at").strip(),
        raw=line,
    )


def read_catalog(vault: Vault, category: str) -> list[CatalogEntry]:
    """入参：vault 与分类。出参：catalog 条目列表；文件不存在时返回空列表。"""
    path = catalog_path(vault, category)
    if not path.is_file():
        return []
    entries: list[CatalogEntry] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        entry = parse_catalog_line(line)
        if entry is not None:
            entries.append(entry)
    return entries


def generate_catalog(vault: Vault, category: str) -> Path:
    """入参：vault 与分类。出参：写出的 catalog 路径。生成一行一节点的可 grep 目录。"""
    if category not in CATEGORIES:
        raise ValueError(f"未知分类: {category}")
    rows = Index(vault.root).rows_for_category(category)
    lines = [GENERATED_HEADER, ""]
    for row in rows:
        lines.append(
            render_catalog_line(
                node_id=str(row["id"]),
                title=str(row["title"]),
                status=str(row["status"]),
                confidence=float(row["confidence"]),
                updated_at=str(row["updated_at"]),
            )
        )
    target = catalog_path(vault, category)
    atomic_write_text(target, "\n".join(lines) + "\n")
    return target


def generate_catalogs(vault: Vault) -> dict[str, Path]:
    """入参：vault。出参：分类到 catalog 路径的映射。"""
    return {category: generate_catalog(vault, category) for category in CATEGORIES}


def generate_atlas(vault: Vault) -> Path:
    """入参：vault。出参：写出的 ATLAS 路径。生成 ≤200 行的顶层导航。"""
    index = Index(vault.root)
    counts = index.counts()
    tags = index.tag_counts(limit=ATLAS_TAG_LIMIT)
    recent = index.recent_rows("2000-01-01T00:00:00+00:00", limit=ATLAS_RECENT_LIMIT)
    lines = [GENERATED_HEADER, "", "# ATLAS", ""]
    lines.append("## 概览")
    lines.append(f"- 节点总数: {counts['total']}")
    lines.append(
        "- 层级: " + " / ".join(f"{layer} {counts['layers'].get(layer, 0)}" for layer in LAYERS)
    )
    lines.append(
        "- 分类: " + " / ".join(f"{cat} {counts['categories'].get(cat, 0)}" for cat in CATEGORIES)
    )
    lines.append(
        "- 状态: "
        + " / ".join(f"{status} {counts['statuses'].get(status, 0)}" for status in STATUSES)
    )
    lines.append(f"- 链接: {counts['links']}")
    lines.append("")
    lines.append("## 目录")
    for category in CATEGORIES:
        count = counts["categories"].get(category, 0)
        lines.append(f"- [{category}](nodes/{category}/_catalog.md)（{count}）")
    lines.append("")
    lines.append("## Top tags")
    if tags:
        chunks = [f"{tag}({count})" for tag, count in tags]
        for start in range(0, len(chunks), 10):
            lines.append("- " + ", ".join(chunks[start : start + 10]))
    else:
        lines.append("- （无）")
    lines.append("")
    lines.append("## 最近更新")
    if recent:
        for row in recent:
            lines.append(
                f"- {row['updated_at']} [{row['title']}]({row['path']}) — "
                f"{row['layer']}/{row['category']} {row['status']}"
            )
    else:
        lines.append("- （无）")
    if len(lines) > ATLAS_MAX_LINES:
        lines = lines[: ATLAS_MAX_LINES - 1] + [f"…（ATLAS 超过 {ATLAS_MAX_LINES} 行已截断）"]
    target = vault.atlas_dir / "ATLAS.md"
    atomic_write_text(target, "\n".join(lines) + "\n")
    return target


def generate(vault: Vault) -> dict[str, str]:
    """入参：vault。出参：生成物相对路径映射。生成失败抛异常，由调用方决定是否阻塞。"""
    paths = generate_catalogs(vault)
    paths["atlas"] = generate_atlas(vault)
    return {key: vault.relative(value) for key, value in paths.items()}
